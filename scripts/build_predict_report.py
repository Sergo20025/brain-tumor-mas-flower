from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Cm, Pt


ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = ROOT / "reports"
DOCX_PATH = OUTPUT_DIR / "Приложение_по_модулю_predict.docx"
TXT_PATH = OUTPUT_DIR / "Приложение_по_модулю_predict.txt"


REPORT_TEXT = """ПРИЛОЖЕНИЕ ПО МОДУЛЮ ПРЕДСКАЗАНИЯ MRI-ИЗОБРАЖЕНИЙ

1. Назначение модуля

В проекте реализован отдельный модуль пользовательского предсказания MRI-изображений, запускаемый скриптом predict_image.py. Его задача состоит в том, чтобы загрузить ранее обученный чекпоинт модели, принять на вход MRI-снимок и выдать результат классификации по четырем классам: glioma, meningioma, pituitary, notumor.

В отличие от тренировочного контура, модуль предсказания ориентирован на практическое использование. Пользователь может либо выбрать изображение через проводник Windows, либо передать путь к файлу напрямую через аргумент командной строки. После этого система показывает изображение, итоговый класс, процент уверенности и вероятности по всем классам.

2. Как работает предсказание

Логика работы модуля предсказания состоит из нескольких этапов:

1. Загружается чекпоинт лучшей модели из папки выбранного эксперимента.
2. Восстанавливается архитектура EfficientNet-B0 с нужным числом классов.
3. Изображение приводится к размеру 224x224 и нормализуется теми же статистиками, что использовались при обучении.
4. Выполняется прямой проход модели.
5. Логиты преобразуются в вероятности при помощи softmax.
6. Пользователю выводится класс с максимальной вероятностью и распределение по остальным классам.

Таким образом, модуль predict использует ровно ту же модель и ту же схему предобработки, что и во время экспериментов, что обеспечивает корректность инференса.

3. Основной чекпоинт для предсказания

Для практического модуля предсказания наиболее целесообразно использовать чекпоинт из эксперимента full_graph для Brain Tumor MRI, так как этот эксперимент показал лучшие итоговые метрики среди агентных децентрализованных вариантов:

- accuracy = 0.8450
- f1_macro = 0.8388
- loss = 0.4958

Команда запуска предсказания с этим чекпоинтом:

python .\\scripts\\predict_image.py --checkpoint .\\outputs\\experiments\\decentralized\\exp_decentralized_full_graph\\checkpoints\\best_model.pt --dataset-root brain_tumor_mri

4. Пример 1: уверенное предсказание

В одном из тестов модуль предсказания обработал изображение Te-gl_356.jpg и выдал результат:

- предсказанный класс: glioma
- уверенность модели: 99.50%
- распределение вероятностей:
  - glioma: 99.50%
  - meningioma: 0.48%
  - notumor: 0.02%
  - pituitary: 0.00%

Данный пример соответствует высокоуверенному предсказанию. Практически вся вероятность сосредоточена в одном классе, а альтернативные варианты почти не рассматриваются моделью. Это означает, что для данного изображения признаки опухоли хорошо совпали с образами класса glioma, усвоенными моделью в ходе обучения.

5. Пример 2: корректное, но менее уверенное предсказание

В другом тесте модуль обработал изображение Te-me_48.jpg и выдал:

- предсказанный класс: meningioma
- уверенность модели: 66.06%
- распределение вероятностей:
  - meningioma: 66.06%
  - glioma: 24.92%
  - pituitary: 9.02%
  - notumor: 0.00%

Этот результат также можно считать корректным, однако уверенность модели заметно ниже. В данном случае модель выбирает класс meningioma, но при этом частично «сомневается» между meningioma и glioma. Подобная ситуация характерна для сложных изображений, при которых признаки нескольких типов опухолей визуально частично перекрываются.

6. Интерпретация уровня уверенности

Процент, выводимый в интерфейсе, является не общей точностью модели на тестовом наборе, а индивидуальной уверенностью softmax для конкретного изображения. Поэтому возможна ситуация, когда:

- модель в целом имеет accuracy около 0.84 на тестовой выборке;
- но на отдельном снимке показывает уверенность 40–70%.

Это не обязательно означает ошибку. Низкая уверенность при правильном предсказании чаще всего говорит о том, что:

- изображение похоже сразу на несколько классов;
- снимок отличается по качеству, яркости или ракурсу от типичных обучающих примеров;
- модель плохо откалибрована по вероятностям;
- классификация выполняется по всему кадру, а не по выделенной области опухоли.

По этой причине вероятность в интерфейсе следует интерпретировать именно как меру уверенности модели в конкретном решении, а не как гарантированную вероятность медицинской истинности диагноза.

7. Практический вывод по модулю predict

Модуль предсказания в текущей реализации можно считать работоспособным. Он:

- корректно загружает чекпоинты обученной модели;
- позволяет пользователю выбирать MRI-изображения через графический интерфейс;
- визуализирует входной снимок;
- выводит наиболее вероятный диагноз;
- показывает вероятности по всем классам.

На уверенных примерах модель демонстрирует высокую концентрацию вероятности на одном классе. На пограничных примерах предсказание может оставаться правильным, но сопровождаться умеренной уверенностью. Это соответствует общей логике работы нейросетевого классификатора и не противоречит результатам проведенных экспериментов.

8. Как можно улучшить модуль в будущем

Перспективные направления развития модуля predict следующие:

- добавить пометку «предсказание неуверенное» при confidence ниже заданного порога;
- выводить второй по вероятности класс как альтернативную гипотезу;
- использовать предобученные веса модели в отдельном режиме;
- применять test-time augmentation;
- перейти от простой классификации к схеме с локализацией или сегментацией опухоли.

Итоговый вывод:

Модуль predict успешно интегрирован в систему и позволяет использовать результаты децентрализованного обучения в прикладном сценарии индивидуальной классификации MRI-изображений. Несмотря на то что уровень уверенности на отдельных изображениях может варьироваться, модуль демонстрирует согласованное поведение и является логическим завершением разработанного программного комплекса.
"""


def configure_styles(document: Document) -> None:
    style = document.styles["Normal"]
    style.font.name = "Times New Roman"
    style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    style.font.size = Pt(12)
    for style_name in ("Heading 1", "Heading 2"):
        heading_style = document.styles[style_name]
        heading_style.font.name = "Times New Roman"
        heading_style._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def add_title(document: Document, text: str) -> None:
    p = document.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(text)
    run.bold = True
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(16)


def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    TXT_PATH.write_text(REPORT_TEXT, encoding="utf-8")

    document = Document()
    configure_styles(document)
    section = document.sections[0]
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(1.5)
    section.top_margin = Cm(2.0)
    section.bottom_margin = Cm(2.0)

    lines = REPORT_TEXT.strip().split("\n\n")
    add_title(document, lines[0])
    for block in lines[1:]:
        rows = block.split("\n")
        head = rows[0]
        if head and head[0].isdigit() and ". " in head:
            document.add_heading(head, level=1)
            for row in rows[1:]:
                document.add_paragraph(row)
        else:
            for row in rows:
                document.add_paragraph(row)

    document.save(DOCX_PATH)
    print(f"Saved TXT report to: {TXT_PATH}")
    print(f"Saved DOCX report to: {DOCX_PATH}")


if __name__ == "__main__":
    main()
